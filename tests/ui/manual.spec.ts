import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { defaultRules } from '../../src/shared/contracts';

const headers = { 'X-JevClean-Token': 'a'.repeat(64) };
test('a saved unclassified snapshot supports manual processing without AI, destination repair and undo', async ({ page }) => {
  test.setTimeout(60000);
  const initial = (await (await page.request.get('/api/bootstrap', { headers })).json()).value;
  await page.request.post('/api/forget', { headers, data: {} });
  await page.request.post('/api/config', { headers, data: { settings: { ...initial.config.settings, email: 'manual@example.com', host: 'missing-target.example.com', rules: defaultRules, mailboxes: ['INBOX'], scanLimit: 100, actionFolders: {}, language: 'zh-CN' }, imapPassword: 'synthetic-only' } });
  let scans = 0; let manualExecutions = 0;
  page.on('request', request => { const path = new URL(request.url()).pathname; if (path === '/api/scan' || path === '/api/test-jev') scans++; if (path === '/api/manual-execute') manualExecutions++; });
  await page.goto('/#session=' + 'a'.repeat(64));
  // Seed an older local snapshot through the API; the new UI intentionally has no read-mail entry.
  await page.request.post('/api/read-mail', { headers, data: {} });
  await page.reload();
  const back = page.getByRole('button', { name: '返回邮件', exact: true });
  if (await back.isVisible()) await back.click();
  await page.locator('.result-filters').getByRole('button', { name: '全部邮件', exact: true }).click();
  await expect(page.getByRole('button', { name: '开始分析', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: '只读取邮件', exact: true })).toHaveCount(0);
  const order = page.locator('.mail-row').filter({ hasText: '订单付款成功，请保留' });
  const activity = page.locator('.mail-row').filter({ hasText: '未知结束时间的活动' });
  await expect(order.getByRole('checkbox')).toBeEnabled(); await expect(order.locator('.mail-verdict')).toHaveCount(0);
  await order.getByRole('checkbox').check(); await activity.getByRole('checkbox').check();
  await expect(page.locator('.selection-bar .rule-action')).toBeDisabled();
  await page.locator('.manual-toolbar').getByRole('button', { name: '归档', exact: true }).click();
  const confirmation = page.getByRole('region', { name: '手动处理', exact: true });
  await expect(confirmation).toContainText('归档到「Archive」');
  await confirmation.getByRole('button', { name: '确认处理', exact: true }).click();
  await expect(order.getByText('已移到「Archive」', { exact: true })).toBeVisible({ timeout: 20000 });
  await expect(order.locator('.mail-verdict')).toHaveCount(0);
  await expect(order.getByText('手动处理：归档', { exact: true })).toBeVisible();
  await expect(page.locator('.messages [role="status"]')).toHaveText('整理完成，共处理 2 封邮件。');
  await page.getByRole('button', { name: '核对结果', exact: true }).click();
  await expect(page.getByText('整理结果已更新。', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '撤销整理', exact: true }).click();
  await expect(order.getByText('已撤销', { exact: true })).toBeVisible({ timeout: 20000 });
  await order.getByRole('checkbox').check();
  await page.locator('.manual-toolbar').getByRole('button', { name: '删除', exact: true }).click();
  await expect(confirmation.locator('.error-text').getByText('请选择删除邮件后的存放位置。', { exact: true })).toBeVisible();
  await expect(confirmation.getByRole('list', { name: '所选邮件' }).getByText('请选择删除邮件后的存放位置。', { exact: true })).toBeVisible();
  await confirmation.getByLabel('存放位置').selectOption('Trash');
  await confirmation.getByRole('button', { name: '保存检查', exact: true }).click();
  await expect(confirmation).toContainText('删除后移到「Trash」');
  await confirmation.getByRole('button', { name: '确认处理', exact: true }).click();
  await expect(order.getByText('已移到「Trash」', { exact: true })).toBeVisible({ timeout: 20000 });
  await page.getByRole('button', { name: '撤销整理', exact: true }).click();
  await expect(order.getByText('已撤销', { exact: true })).toBeVisible({ timeout: 20000 });
  expect(scans).toBe(0); expect(manualExecutions).toBe(2);
  const saved = (await (await page.request.get('/api/bootstrap', { headers })).json()).value;
  expect(saved.config.hasJevApiKey).toBe(false); expect(saved.report.apiCalls).toBe(0); expect(saved.config.settings.rules).toEqual(defaultRules);
  await page.setViewportSize({ width: 390, height: 844 }); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('keep and review selections support manual move and flags despite stale rules, while AI evidence is retained', async ({ page }) => {
  test.setTimeout(60000);
  const initial = (await (await page.request.get('/api/bootstrap', { headers })).json()).value;
  await page.request.post('/api/config', { headers, data: { settings: { ...initial.config.settings, host: 'imap.example.com', actionFolders: {}, rules: defaultRules, language: 'zh-CN' }, imapPassword: 'synthetic-only', jevApiKey: 'synthetic-key' } });
  await page.goto('/#session=' + 'a'.repeat(64));
  await page.getByLabel('同意向 Jev 发送邮件文字。包括主题、发件人和正文。').check();
  await page.getByRole('button', { name: '开始分析', exact: true }).click();
  await expect(page.getByText(/^分析完成，共 .*查看结果，选好邮件后点击「整理」。$/)).toBeVisible();
  const before = (await (await page.request.get('/api/bootstrap', { headers })).json()).value;
  const orderEvidence = before.report.records.find((record: { subject: string }) => record.subject === '订单付款成功，请保留');
  const evidence = (record: typeof orderEvidence) => JSON.stringify(['category', 'reason', 'probability', 'verdicts', 'action', 'matchedRules'].map(key => record[key]));
  let scans = 0; page.on('request', request => { if (new URL(request.url()).pathname === '/api/scan') scans++; });
  await page.getByRole('button', { name: '暂不整理', exact: true }).click();
  const order = page.locator('.mail-row').filter({ hasText: '订单付款成功，请保留' });
  await order.getByRole('checkbox').check(); await expect(page.locator('.selection-bar .rule-action')).toBeDisabled();
  await page.getByRole('button', { name: '待查看', exact: true }).click();
  const review = page.locator('.mail-row').filter({ hasText: '未知结束时间的活动' });
  await page.locator('.result-filters').getByRole('button', { name: '全部邮件', exact: true }).click();
  await order.getByRole('checkbox').check(); await review.getByRole('checkbox').check();
  await page.locator('.manual-toolbar').getByRole('button', { name: '移动', exact: true }).click();
  const panel = page.getByRole('region', { name: '手动处理', exact: true });
  await panel.getByRole('button', { name: '检查处理', exact: true }).isDisabled().then(value => expect(value).toBe(true));
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.locator('.manual-toolbar').getByRole('button', { name: '移动', exact: true }).click();
  await panel.getByLabel('存放位置').selectOption('Archive');
  await panel.getByRole('button', { name: '检查处理', exact: true }).click();
  await panel.getByRole('button', { name: '确认处理', exact: true }).click();
  await page.locator('.result-filters').getByRole('button', { name: '全部邮件', exact: true }).click();
  await expect(order.getByText('已移到「Archive」', { exact: true })).toBeVisible({ timeout: 20000 });
  await expect(order.locator('.action-badge')).toHaveText('保留');
  await expect(review.locator('.action-badge')).toHaveText('待查看');
  if (process.env.JEVCLEAN_MANUAL_CAPTURES) {
    await mkdir('.impeccable/review', { recursive: true });
    await page.evaluate(() => { document.querySelector('.account-label')?.append(' · Synthetic mail example / 合成邮件示例'); });
    for (const width of [1440, 390]) {
      await page.setViewportSize({ width, height: 1000 });
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      await page.screenshot({ path: '.impeccable/review/manual-results-zh-' + width + '.png', fullPage: true, animations: 'disabled' });
      await page.screenshot({ path: width === 1440 ? 'docs/images/review-example.png' : 'docs/images/narrow-layout.png', fullPage: true, animations: 'disabled' });
    }
    await page.setViewportSize({ width: 1320, height: 1000 });
  }
  const after = (await (await page.request.get('/api/bootstrap', { headers })).json()).value;
  expect(after.report.apiCalls).toBe(before.report.apiCalls); expect(evidence(after.report.records.find((record: { id: string }) => record.id === orderEvidence.id))).toBe(evidence(orderEvidence));
  await page.getByRole('button', { name: '撤销整理', exact: true }).click();
  await expect(order.getByText('已撤销', { exact: true })).toBeVisible({ timeout: 20000 });
  const saved = (await (await page.request.get('/api/bootstrap', { headers })).json()).value;
  await page.request.post('/api/config', { headers, data: { settings: { ...saved.config.settings, rules: saved.config.settings.rules.map((rule: { description: string }) => ({ ...rule, description: rule.description + '这是新的条件。' })), language: 'en' } } });
  await page.reload(); await page.locator('.result-filters').getByRole('button', { name: 'All mail', exact: true }).click();
  await expect(page.getByText('Rules or scope have changed. Start analysis again. You can still manually process loaded emails.', { exact: true })).toBeVisible();
  const englishOrder = page.locator('.mail-row').filter({ hasText: '订单付款成功，请保留' }); await englishOrder.getByRole('checkbox').check();
  await expect(page.locator('.selection-bar .rule-action')).toBeDisabled();
  await page.locator('.manual-toolbar').getByRole('button', { name: 'Mark as read', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm action', exact: true }).click();
  await expect(englishOrder.getByText('Read', { exact: true })).toBeVisible(); await expect(englishOrder.locator('.action-badge')).toHaveText('Keep');
  await page.getByRole('button', { name: 'Undo organization', exact: true }).click();
  await expect(englishOrder.getByText('Undone', { exact: true })).toBeVisible(); expect(scans).toBe(0);
  await page.setViewportSize({ width: 390, height: 844 }); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
